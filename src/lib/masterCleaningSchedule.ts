const ROOM_CARE = "Room Care R3";
const LIGHT_TRAPS_FREQ = "1x/week (winter), 2x/week (summer)";

function zone(key: string, title: string, rows: [string, string, string?, string?][]): CleaningZone {
  return {
    key,
    title,
    tasks: rows.map(([item, tools, chemical, frequency], i) => ({
      key: `${key}-${i + 1}`,
      item,
      tools,
      chemical,
      frequency: frequency ?? "Daily",
    })),
  };
}

