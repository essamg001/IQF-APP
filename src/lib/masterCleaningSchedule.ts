export const MASTER_CLEANING_TASK_COUNT = MASTER_CLEANING_SCHEDULE.reduce((n, z) => n + z.tasks.length, 0);

export function findCleaningTask(taskKey: string): { zone: CleaningZone; task: CleaningTask } | null {
  for (const z of MASTER_CLEANING_SCHEDULE) {
    const task = z.tasks.find((t) => t.key === taskKey);
    if (task) return { zone: z, task };
  }
  return null;
}
