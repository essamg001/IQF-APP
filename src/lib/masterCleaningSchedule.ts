// HSE03297 (Packhouse 11 / IQF 1) and HSE03312 (Packhouse 13 / IQF 2) --
// the master sanitation schedule. Both packhouses run the same schedule
// (same items, tools, chemicals, frequencies), so this one list is shared
// and logged per-factory via MasterCleaningTaskLog.taskKey.
export type CleaningTask = {
  key: string;
  item: string;
  tools: string;
  chemical?: string;
  frequency: string;
};

export type CleaningZone = {
  key: string;
  title: string;
  tasks: CleaningTask[];
};

const STD = "Novaclean Soap 1% / Clint KF200 1% + Clari Chlorine-L 2% / Raed Chlorine 2%";
